#!/usr/bin/env node
// ============================================================================
// OneLink — scripts/sync-dev-vars.mjs
//
// WHY THIS EXISTS
//
// `wrangler dev` resolves `.dev.vars` relative to the directory that holds
// wrangler.jsonc (`apps/api/`), NOT the directory npm was run from:
//
//     const devVarsPath = path.resolve(configDir, ".dev.vars")
//
// The canonical file is the one at the repository root — that is the one you
// edit by hand, and the one scripts/seed-owner.mjs reads credentials from. So
// this materialises a copy next to the config before wrangler starts, and every
// `npm run dev` refreshes it.
//
// WHY A MISSING SOURCE IS A HARD FAILURE
//
// The committed `vars.ENVIRONMENT` is `production`, and production refuses to
// run without a real SESSION_PEPPER. With no `.dev.vars` at all, a local
// `wrangler dev` answers 500 INTERNAL to every request — /api/v1/health
// included — which reads exactly like a code bug. Failing here turns that into
// one obvious message instead.
// ============================================================================
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const API_ROOT = path.resolve(HERE, '..')
const SOURCE = path.resolve(API_ROOT, '..', '..', '.dev.vars')
const DEST = path.join(API_ROOT, '.dev.vars')

const GENERATED_MARKER = '# GENERATED from'

const HEADER = `${GENERATED_MARKER} ../../.dev.vars by apps/api/scripts/sync-dev-vars.mjs
#
# Do NOT edit this file. wrangler reads .dev.vars from the directory holding
# wrangler.jsonc, so a copy has to exist here — but the file you edit is the one
# at the repository root. Changes made here are overwritten by the next
# npm run dev, and then silently diverge from the credentials seed-owner.mjs
# hashes into the database.
# --------------------------------------------------------------------------
`

/** Minimal KEY=VALUE reader (comments and blank lines ignored). */
function parseDotEnv(text) {
  const out = {}
  for (const raw of text.split('\n')) {
    const line = raw.trim()
    if (line === '' || line.startsWith('#')) continue
    const eq = line.indexOf('=')
    if (eq <= 0) continue
    out[line.slice(0, eq).trim()] = line.slice(eq + 1).trim()
  }
  return out
}

/**
 * A local environment that is not `development` is a deliberate choice sometimes
 * (testing production semantics), so this warns rather than fails — but the
 * consequence is invisible otherwise: no devToken in password-reset responses,
 * and a missing SESSION_PEPPER 500s every request.
 */
function reportEnvironment(value) {
  if (value === 'development') return
  console.warn('')
  console.warn(`  warning    : ENVIRONMENT is ${value === '' ? 'unset' : `"${value}"`} in .dev.vars, not "development".`)
  console.warn('               Locally that means production semantics: a real SESSION_PEPPER')
  console.warn('               is required (otherwise every request answers 500), and')
  console.warn('               password-reset responses will not include a devToken.')
  console.warn('')
}

if (!existsSync(SOURCE)) {
  console.error('')
  console.error('  Cannot create apps/api/.dev.vars: there is no .dev.vars at the repository root.')
  console.error('')
  console.error(`  expected: ${SOURCE}`)
  console.error('')
  console.error('  Without it `wrangler dev` runs as production (the committed default) with no')
  console.error('  SESSION_PEPPER, so every request — /api/v1/health included — answers 500 INTERNAL.')
  console.error('')
  console.error('  Fix, from the repository root:')
  console.error('    copy .dev.vars.example .dev.vars        (POSIX: cp .dev.vars.example .dev.vars)')
  console.error('')
  process.exit(1)
}

const source = readFileSync(SOURCE, 'utf8').replace(/\r\n/g, '\n')
const body = source.endsWith('\n') ? source : `${source}\n`
const content = `${HEADER}\n${body}`

const parsed = parseDotEnv(source)
const keyCount = Object.keys(parsed).length

if (existsSync(DEST)) {
  const existing = readFileSync(DEST, 'utf8').replace(/\r\n/g, '\n')
  if (existing === content) {
    console.log(`  .dev.vars  : apps/api/.dev.vars already in sync with the root .dev.vars (${keyCount} keys)`)
    reportEnvironment(parsed.ENVIRONMENT ?? '')
    process.exit(0)
  }
  if (!existing.includes(GENERATED_MARKER)) {
    console.warn('  .dev.vars  : replacing a hand-written apps/api/.dev.vars — edit the root .dev.vars instead.')
  }
}

writeFileSync(DEST, content, 'utf8')
console.log(`  .dev.vars  : wrote apps/api/.dev.vars from the root .dev.vars (${keyCount} keys)`)
reportEnvironment(parsed.ENVIRONMENT ?? '')
